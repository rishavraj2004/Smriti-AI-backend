export const generateMathGame = (difficulty = 1, lang = "en") => {
  const qCounts = { 1: 4, 2: 5, 3: 6 };
  const targetCount = qCounts[difficulty] || 4;

  const pool = MATH_QUESTIONS_BANK.filter(q => q.difficulty <= difficulty);
  const selected = [...pool]
    .sort(() => Math.random() - 0.5)
    .slice(0, targetCount)
    .map((q, idx) => ({
      id: idx + 1,
      prompt: q.prompts[lang] || q.prompts.en,
      itemsDisplay: q.itemsDisplay || null,
      correctAnswer: q.correctAnswer,
      options: [...q.options].sort(() => Math.random() - 0.5),
    }));

  return {
    gameType: "math_memory",
    difficulty,
    title: "Gentle Math & Daily Arithmetic",
    instructions: "Solve gentle counting and daily calculations at a comfortable pace.",
    content: {
      questionsCount: selected.length,
      questions: selected,
    },
    settings: {
      timeLimitMs: selected.length * 15000,
      expectedTimeMs: selected.length * 6000,
    },
  };
};
