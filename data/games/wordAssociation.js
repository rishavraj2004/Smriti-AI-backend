export const generateWordAssociationGame = (difficulty = 1, lang = "en") => {
  const qCounts = { 1: 3, 2: 4, 3: 5 };
  const targetCount = qCounts[difficulty] || 3;

  const pool = WORD_ASSOCIATION_BANK.filter(q => q.difficulty <= difficulty);
  const selected = [...pool]
    .sort(() => Math.random() - 0.5)
    .slice(0, targetCount)
    .map((q, idx) => ({
      id: idx + 1,
      prefix: q.prefixes[lang] || q.prefixes.en,
      correctWord: q.correctWords[lang] || q.correctWords.en,
      options: (q.options[lang] || q.options.en).sort(() => Math.random() - 0.5),
      hint: q.hints[lang] || q.hints.en,
    }));

  return {
    gameType: "word_association",
    difficulty,
    title: "Word & Folklore Association",
    instructions: "Choose the phrase or word that culturally and logically completes the pair.",
    content: {
      questionsCount: selected.length,
      questions: selected,
    },
    settings: {
      timeLimitMs: selected.length * 15000,
      expectedTimeMs: selected.length * 5000,
    },
  };
};
