export const generateRoutineRecallGame = (difficulty = 1, lang = "en") => {
  const targetCount = difficulty === 1 ? 2 : difficulty === 2 ? 3 : 4;
  const shuffled = [...ROUTINE_QUESTIONS_BANK].sort(() => Math.random() - 0.5);
  const selected = shuffled.slice(0, targetCount).map((q, idx) => {
    const prompt = q.prompts[lang] || q.prompts.en;
    const correctAnswer = q.correct[lang] || q.correct.en;
    const options = q.options.map(o => o[lang] || o.en).sort(() => Math.random() - 0.5);

    return {
      id: idx + 1,
      time: q.time,
      prompt,
      correctAnswer,
      options,
    };
  });

  return {
    gameType: "routine_recall",
    difficulty,
    title: TITLES[lang] || TITLES.en,
    instructions: INSTRUCTIONS[lang] || INSTRUCTIONS.en,
    content: {
      questionsCount: selected.length,
      questions: selected,
    },
    settings: {
      timeLimitMs: selected.length * 25000,
      expectedTimeMs: selected.length * 10000,
    },
  };
};
